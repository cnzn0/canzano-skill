#!/usr/bin/env python3
"""Generates assets/palette.css: a neutral scale and eleven vivid hue scales in OKLCH.

Each hue gets seven steps (100 lightest to 700 darkest) spread across the lightness band where
that hue is most saturated, at 96% of the highest chroma sRGB allows. Warm hues drift toward
orange as they darken, the way pigment does, so nothing turns brown or olive. There are no pale
tints and no near-black shades: every step is a colour you would pick on purpose.
To add or change a hue, edit HUES and run: python3 scripts/palette.py
"""
import math, pathlib

# name, lightness at step 100, lightness at step 700, hue at step 100, hue at step 700
HUES = [("red", 0.66, 0.46, 27, 27), ("orange", 0.76, 0.58, 52, 40), ("amber", 0.84, 0.66, 78, 55),
        ("yellow", 0.92, 0.76, 100, 78), ("lime", 0.92, 0.70, 126, 138), ("green", 0.86, 0.60, 145, 148),
        ("sky", 0.80, 0.58, 232, 245), ("blue", 0.68, 0.44, 256, 262), ("violet", 0.60, 0.38, 282, 276),
        ("purple", 0.66, 0.42, 305, 305), ("pink", 0.72, 0.50, 345, 350)]
STEPS = [100, 200, 300, 400, 500, 600, 700]
GREYS = [(0, 1), (50, 0.976), (100, 0.96), (150, 0.944), (200, 0.915), (300, 0.871), (400, 0.72),
         (500, 0.557), (600, 0.487), (700, 0.38), (800, 0.293), (900, 0.196), (950, 0.145)]
GREY_HUE, GREY_CHROMA, FILL = 286, 0.003, 0.96

def linear(L, C, h):
    a, b = C * math.cos(math.radians(h)), C * math.sin(math.radians(h))
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
            -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
            -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)

def max_chroma(L, h):
    c = 0.0
    while c < 0.4 and all(-0.0005 <= v <= 1.0005 for v in linear(L, c + 0.001, h)):
        c += 0.001
    return c

def contrast(L, C, h, page):
    r, g, b = (min(1, max(0, v)) for v in linear(L, C, h))
    y = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return (max(y, page) + 0.05) / (min(y, page) + 0.05)

DARK_PAGE = 0.0027  # luminance of grey-950

out = ["/* canzano palette. Generated by scripts/palette.py; do not edit by hand.",
       "   Raw scales only. Pages use the semantic tokens in tokens.css, which point here.",
       "   The comment after each colour is its contrast on white / on the dark page. */", "", ":root {"]
out.append("  /* grey: a faint cool tint, hue %d */" % GREY_HUE)
for n, L in GREYS:
    c = 0 if n == 0 else min(GREY_CHROMA, max_chroma(L, GREY_HUE))
    out.append(f"  --grey-{n}: oklch({L:g} {c:g} {GREY_HUE if c else 0});")
for name, l1, l7, h1, h7 in HUES:
    out.append(f"\n  /* {name} */")
    for i, n in enumerate(STEPS):
        t = i / (len(STEPS) - 1)
        L, h = round(l1 + (l7 - l1) * t, 3), round(h1 + (h7 - h1) * t, 1)
        c = round(max_chroma(L, h) * FILL, 3)
        out.append(f"  --{name}-{n}: oklch({L:g} {c:g} {h:g}); /* {contrast(L, c, h, 1):.1f} / {contrast(L, c, h, DARK_PAGE):.1f} */")
out.append("}\n")
path = pathlib.Path(__file__).resolve().parent.parent / "assets" / "palette.css"
path.write_text("\n".join(out))
print(path, len(HUES) * len(STEPS) + len(GREYS), "colours")
